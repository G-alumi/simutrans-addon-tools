/**
 * ひな形をスニペットにする
 * - 値が空: 入力欄。値がある: その値が入った入力欄
 * - a|b|c と、決まった語のキー: 候補から選ぶ(書いてある値が最初)
 * - 画像の image.行.列: image の部分が入力欄で、ほかの画像の行も同じ名前になる
 * - obj= はそのまま
 */
export function templateSnippet(text: string): string {
	const obj = /^obj=(.*)$/m.exec(text)?.[1].trim();
	let next = 1;
	let image: number | undefined;
	return text.split('\n').map((line) => {
		const eq = line.indexOf('=');
		if (eq < 0 || line.startsWith('obj=')) {
			return escape(line);
		}
		const head = escape(line.slice(0, eq + 1));
		const value = line.slice(eq + 1);
		const def = findKeyDef(obj, line.slice(0, eq).toLowerCase());
		const img = def?.value === 'image' ? /^(>?\s*)image(\..*)$/.exec(value) : null;
		if (img) {
			image ??= next++;
			return `${head}${escape(img[1])}\${${image}:image}${escape(img[2])}`;
		}
		const words = value !== '' && typeof def?.value === 'object' && 'words' in def.value ? def.value.words : undefined;
		const choices = value.includes('|') ? value.split('|') : words ? [value, ...words.filter((w) => w !== value)] : undefined;
		if (choices) {
			return `${head}\${${next++}|${choices.map((c) => c.replace(/[,|\\]/g, '\\$&')).join(',')}|}`;
		}
		return `${head}\${${next++}${value === '' ? '' : ':' + escape(value)}}`;
	}).join('\n');
}

/** スニペットで特別な意味を持つ文字 */
function escape(s: string): string {
	return s.replace(/[$}\\]/g, '\\$&');
}
